#ifndef AXIPC_H
#define AXIPC_H

/*
 * ============================================================
 * axipc.h -- общие типы событий и API окон ArtyomX64
 * ============================================================
 *
 * МОДЕЛЬ NeXTSTEP / MacOS X:
 *
 *   GUI живёт в ОТДЕЛЬНОМ процессе-сервере (wserver, аналог
 *   WindowServer).  Приложения-клиенты НЕ вызывают GUI-сисколлы
 *   ядра: они общаются с wserver через порты сообщений
 *   (lib/axport.h, сисколлы 178-181), а канвас рисуют в
 *   разделяемой памяти.
 *
 * Этот заголовок -- общая часть ABI клиента и сервера:
 * события, коды клавиш, описание меню.  Сиколлов GUI здесь
 * больше нет: 160-166, 168-177 удалены из ядра.  Из
 * "системных" остались только порты/SHM/tty/ввод (axport.h).
 */

#include <stdint.h>

/* Registered menubar limits (enforced by the server). */
#define AX_APP_MENUS_MAX   4
#define AX_MENU_ITEMS_MAX  6
#define AX_MENU_TITLE_MAX  16
#define AX_MENU_ITEM_MAX   24

/* App-menu items rendered by the server for every app. */
#define AX_APPITEM_ABOUT 0
#define AX_APPITEM_HIDE  1
#define AX_APPITEM_QUIT  2

/*
 * Пользовательское описание меню (ax_menu_set()).  Все указатели
 * ссылаются на память приложения; сервер копирует строки при
 * получении сообщения MSG_REQ_MENU_SET.
 *
 *     static const char *file_items[] = { "New Window", "Close Window" };
 *     static const ax_menu_def_t menus[] = {
 *         { "File",  file_items, 2 },
 *     };
 *     static const ax_menubar_def_t mb = { "Notes", menus, 1 };
 *     ax_menu_set(&mb);
 */
typedef struct {
    const char *title;    /* "File", "Edit", ...                   */
    const char **items;   /* item labels (item_count entries)      */
    uint32_t    item_count;
} ax_menu_def_t;

typedef struct {
    const char    *app_name;    /* bold label next to the logo */
    const ax_menu_def_t *menus;
    uint32_t       menu_count;
} ax_menubar_def_t;

/*
 * Проволочный (wire) формат меню для MSG_REQ_MENU_SET --
 * плоская структура без указателей.
 */
typedef struct {
    char app_name[20];
    uint32_t menu_count;
    struct {
        char title[AX_MENU_TITLE_MAX];
        uint32_t item_count;
        char items[AX_MENU_ITEMS_MAX][AX_MENU_ITEM_MAX];
    } menus[AX_APP_MENUS_MAX];
} ax_menubar_wire_t;

#define AX_EV_NONE   0
#define AX_EV_KEY    1
#define AX_EV_MOUSE  2
#define AX_EV_CLOSE  3
#define AX_EV_RESIZE 4
/*
 * macOS-model additions:
 *
 *   AX_EV_NEWWIN -- the global menu (File > New Window) asks the
 *                   ACTIVE app to open one more window in the
 *                   same process.  Single-window apps ignore it.
 *
 *   AX_EV_QUIT   -- the global menu (App menu > Quit) asks the
 *                   app to destroy ALL of its windows and exit
 *                   the process (Cmd+Q).
 *
 *   AX_EV_MENU   -- a click on one of the APP'S OWN menu items
 *                   (registered via ax_menu_set).  Delivered
 *                   to the focused window: ev.key = menu index,
 *                   ev.w   = item index (both 0-based).
 */
#define AX_EV_NEWWIN 5
#define AX_EV_QUIT   6
#define AX_EV_MENU   7

/*
 * AX_EV_RAWKEY -- "сырое" событие клавиатуры для игр (DOOM).
 *
 * Обычный AX_EV_KEY доставляет только НАЖАТИЯ и только в виде
 * ASCII, поэтому игры не могут узнать, что клавиша отпущена
 * (нельзя идти, удерживая W).  AX_EV_RAWKEY приходит на каждое
 * make/break и передаёт сканкод как есть:
 *
 *     ev.key     -- сканкод set 1 (0x00..0x7F)
 *     ev.buttons -- 1, если клавиша расширенная (префикс 0xE0:
 *                   стрелки, правый Ctrl/Alt, keypad), иначе 0
 *     ev.w       -- 1 = нажатие, 0 = отпускание
 *
 * Сервер шлёт AX_EV_RAWKEY ВСЕГДА вместе с обычной трансляцией
 * (AX_EV_KEY), так что старые приложения не затронуты.  Событие
 * получает только сфокусированное окно -- как и AX_EV_KEY.
 */
#define AX_EV_RAWKEY 8

/*
 * Special key codes delivered in ax_event.key for AX_EV_KEY.
 *
 * AX_KEY_CTRL_S/O/N are generated by the keyboard driver
 * (Ctrl+S -> 0xF1, Ctrl+O -> 0xF4, Ctrl+N -> 0xF5) and mapped
 * by wserver's process_input() into these values.
 */
#define AX_KEY_CTRL_S    0x101
#define AX_KEY_CTRL_O    0x102
#define AX_KEY_CTRL_N    0x103
#define AX_KEY_BACKSPACE 8
#define AX_KEY_ENTER     13

#define AX_KEY_CTRL      0x100

typedef struct {
    uint32_t type;
    uint32_t key;
    int32_t  mx, my;
    uint32_t buttons;
    uint32_t w, h;
} ax_event;

typedef struct {
    int32_t  year, month, day;
    int32_t  hour, minute, second;
} ax_time_t;

typedef struct {
    uint32_t width;
    uint32_t height;
} ax_screen_t;

#endif
